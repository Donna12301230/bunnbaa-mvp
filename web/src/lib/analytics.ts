import { useQuery } from "@tanstack/react-query";
import { collection, doc, getDoc, getDocs, limit, orderBy, query, where } from "firebase/firestore";
import { db } from "@/lib/firebase";
import { todayStr } from "@/lib/pickupSlots";

// Data formats the frontend reads after BigQuery analysis results are written back to Firestore (P1, P2 in doc/GoogleCloud改動建議.md).
// These documents are written by backend schedules with the Admin SDK; the frontend only reads. Without data each screen shows an empty state, and it appears once the backend is wired up.
// The fields are the frontend's first version (2026-10-10); if the backend needs changes, update this file and the "Frontend data formats" section of doc/GoogleCloud改動建議.md.

/**
 * Demand forecast: vendors/{vendorId}/forecast/{YYYY-MM-DD}, one doc per day (BigQuery AI.FORECAST results).
 * Readable by the vendor owner and admins (vendors/{vendorId}/{sub}/{docId} in firestore.rules).
 */
export interface DemandForecast {
  date: string; // pickup date YYYY-MM-DD, same as the doc id
  predicted: number; // forecast portions (AI.FORECAST forecast_value)
  lower?: number; // lower bound of the prediction interval (prediction_interval_lower_bound)
  upper?: number; // upper bound of the prediction interval (prediction_interval_upper_bound)
  generated_at?: unknown; // Firestore Timestamp
}

/**
 * Customer segments: vendors/{vendorId}/segments/{id}, one doc per segment (ML.KMEANS clustering + a description from AI.GENERATE).
 * Aggregate numbers only, no personal data.
 */
export interface CustomerSegment {
  id: string;
  name: string; // segment name, e.g. "Weekday lunch regulars"
  name_en?: string;
  description: string; // one-line description generated by Gemini
  description_en?: string;
  customers: number; // number of customers in this segment
  share?: number; // share of all customers, 0–1 (computed on the client from customers if absent)
  avg_spend?: number; // average paid per order (NT$)
  orders_per_month?: number; // average orders per month
  generated_at?: unknown;
}

/** Looker Studio dashboard URL embedded in the admin console: platformConfig/analytics (admin-writable, publicly readable) */
export interface AnalyticsConfig {
  lookerStudioEmbedUrl?: string;
  /** Old field name (written by another version before the merge); read only, never written */
  looker_embed_url?: string | null;
}

/** What a Looker Studio embed URL looks like; only this domain is accepted so the admin page can't be made to embed another site */
export const LOOKER_EMBED_PREFIX = "https://lookerstudio.google.com/embed/";
export const isLookerEmbedUrl = (url: string) => url.startsWith(LOOKER_EMBED_PREFIX) && url.length <= 500;

const numberOr = (v: unknown, fallback?: number) => (typeof v === "number" && Number.isFinite(v) ? v : fallback);

/** Forecasts for up to 7 days from today, sorted by date; empty array when there's no data */
export function useDemandForecast(vendorId: string | undefined) {
  return useQuery({
    queryKey: ["demandForecast", vendorId, todayStr()],
    queryFn: async (): Promise<DemandForecast[]> => {
      const snap = await getDocs(query(collection(db, "vendors", vendorId!, "forecast"), where("date", ">=", todayStr()), orderBy("date"), limit(7)));
      return snap.docs
        .map((d) => {
          const x = d.data();
          return { date: String(x.date || d.id), predicted: numberOr(x.predicted, NaN)!, lower: numberOr(x.lower), upper: numberOr(x.upper), generated_at: x.generated_at };
        })
        .filter((f) => Number.isFinite(f.predicted) && /^\d{4}-\d{2}-\d{2}$/.test(f.date));
    },
    enabled: !!vendorId,
    staleTime: 10 * 60 * 1000,
  });
}

/** Customer segments, largest first; empty array when there's no data */
export function useCustomerSegments(vendorId: string | undefined) {
  return useQuery({
    queryKey: ["customerSegments", vendorId],
    queryFn: async (): Promise<CustomerSegment[]> => {
      const snap = await getDocs(query(collection(db, "vendors", vendorId!, "segments"), limit(12)));
      const rows = snap.docs
        .map((d) => ({ id: d.id, ...(d.data() as Omit<CustomerSegment, "id">) }))
        .filter((s) => typeof s.name === "string" && s.name && numberOr(s.customers, 0)! > 0);
      const total = rows.reduce((sum, s) => sum + s.customers, 0);
      return rows
        .map((s) => ({ ...s, share: numberOr(s.share) ?? (total > 0 ? s.customers / total : 0) }))
        .sort((a, b) => b.customers - a.customers);
    },
    enabled: !!vendorId,
    staleTime: 30 * 60 * 1000,
  });
}

export const analyticsConfigKey = ["analyticsConfig"] as const;
export function useAnalyticsConfig() {
  return useQuery({
    queryKey: analyticsConfigKey,
    queryFn: async (): Promise<AnalyticsConfig> => {
      const snap = await getDoc(doc(db, "platformConfig", "analytics"));
      return snap.exists() ? (snap.data() as AnalyticsConfig) : {};
    },
  });
}
